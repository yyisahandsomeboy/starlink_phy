function writeReport(out, report)
%WRITEREPORT 无外部前端框架/联网依赖的中文图像索引与教学说明。
file=fullfile(out,'index.html');fid=fopen(file,'w','n','UTF-8');assert(fid>=0);closer=onCleanup(@()fclose(fid));
fprintf(fid,['<!doctype html><html lang="zh-CN"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">' ...
    '<title>Starlink教学诊断</title><style>body{font:16px/1.8 "Microsoft YaHei",sans-serif;max-width:1200px;margin:25px auto;padding:0 18px;color:#183144}' ...
    'h1{font-size:30px}h2{font-size:23px}body{overflow-wrap:anywhere}img{max-width:100%%;height:auto;box-sizing:border-box;border:1px solid #ddd}table{border-collapse:collapse;width:100%%;table-layout:fixed}' ...
    'td,th{border-bottom:1px solid #ddd;padding:8px;text-align:left}code{overflow-wrap:anywhere}.card{border:1px solid #d6e1e6;padding:18px;margin:22px 0;border-radius:8px}' ...
    'a{color:#066b91}.note{background:#edf5f8;padding:14px}@media print{.card{break-inside:avoid}}</style>']);
fprintf(fid,'<h1>真实IQ → 接收机教学诊断</h1><p>生成时间：%s；源运行：<code>%s</code></p>',esc(report.generated_at),esc(report.source_run));
fprintf(fid,['<div class="note">本页从保存的MAT重新生成观察结果，不执行DSP。缺少后续步骤时照实标记缺失。' ...
    '候选几何不是商业MCS；没有真实业务BER/SER、FEC或CRC证明。</div>' ...
    '<p><a href="diagnostics_summary.json">统一数值摘要JSON</a> · <a href="diagnostics_data.mat">选区原数值与显示参数MAT</a> · ' ...
    '<a href="point_resources.csv">星座点资源追溯CSV</a></p>']);
if ~isempty(fieldnames(report.sync))
    s=report.sync.selected;
    fprintf(fid,['<div class="card"><h2>先理解同步坐标</h2><p>选中候选 %s：模型一基帧头 %.12g；原文件一基复采样 %.12g；' ...
        '时间 %.9f ms；最近原整数点 %.0f；含小数位置 %d。</p><p>PSS %.9f；SSS %.9f；联合 %.9f；粗CFO %.6f Hz。</p>' ...
        '<p>局部0对应这个帧头，不是原文件采样0。全局曲线每%d点抽取1点，不能当完整分辨率峰值。</p>' ...
        '<p>%s</p><a href="sync_candidates.csv">打开实际候选统计表</a></div>'], ...
        esc(s.candidate_id),s.model_sample,s.raw_sample,s.time_ms,s.nearest_raw_integer,s.has_fractional_raw_position, ...
        s.pss_score,s.sss_score,s.joint_score,s.coarse_cfo_hz,report.sync.trace_decimation,esc(report.sync.selection_rule));
end
fprintf(fid,'<h2>先看什么，再看什么</h2><ol>');
for k=1:numel(report.figures),f=report.figures(k);fprintf(fid,'<li><a href="#%s">%s</a>：%s</li>',f.key,esc(f.title),esc(f.purpose));end
fprintf(fid,'</ol><h2>同资源、同轮次的指标</h2><table><tr><th>阶段</th><th>可用</th><th>原单位EVM/%%</th><th>SSS约定EVM/%%</th><th>参考标定说明</th></tr>');
for k=1:numel(report.pilots.records)
    p=report.pilots.records(k);
    fprintf(fid,'<tr><td>%s</td><td>%d</td><td>%.6g</td><td>%.6g</td><td>%s</td></tr>',p.stage,p.available,100*p.raw_evm,100*p.calibrated_evm,esc(p.calibration_source));
end
fprintf(fid,['</table><p>FFT整体复增益只用SSS估计，除法仅用于诊断参考标定，未改变接收机输出；EVAL未参加标定。' ...
    'EVM=sqrt(sum|Z−P|²/sum|P|²)。原数值与复除数保存在MAT/JSON。不能将EVM当成业务误码率。</p>']);
if ~isempty(report.missing_checkpoints)
    fprintf(fid,'<p class="note">尚缺检查点：%s。对应空面板不是成功结果。</p>',esc(strjoin(report.missing_checkpoints,', ')));
end
for k=1:numel(report.figures)
    f=report.figures(k);
    fprintf(fid,['<section class="card" id="%s"><h2>%s</h2><p><b>想验证什么：</b>%s</p><p><b>坐标与单位：</b>%s</p>' ...
        '<img loading="lazy" src="%s" alt="%s"><p><b>正常/诊断现象：</b>%s</p>' ...
        '<p><b>当前实际结果：</b>%s</p><p><b>不能证明：</b>%s</p><p>源码：<code>%s</code></p></section>'], ...
        f.key,esc(f.title),esc(f.purpose),esc(f.axes),f.file,esc(f.title), ...
        esc(f.normal_or_diagnostic_pattern),esc(f.current_fact),esc(f.limitations),esc(f.source));
end
fprintf(fid,['<h2>点如何回到IQ</h2><p>点的CSV给出轮次、数据符号、网格列、MATLAB行、signed bin、MHz、原复数和显示除数。' ...
    'MAT保存所选符号的1024份实际插值位置。FFT点不是唯一ADC采样；其值组合整段时间采样，还经过sinc/FIR。' ...
    '均衡/跟踪还依赖SSS和整帧参数，区间不是完整算法依赖。</p><h2>MATLAB交互</h2>' ...
    '<p>全局同步窗口可切换原采样/ms/模型坐标；FFT图可切换bin/MHz；星座数据光标可查看资源位置。' ...
    '运行<code>BROWSE_DIAGNOSTICS(runDir)</code>切换帧、符号、频段和显示归一化。静态PNG保持默认坐标，交互请打开MATLAB窗口。</p>' ...
    '<p>修改后重新运行请新建输出目录；本页不覆盖历史实验。</p></html>']);
% 同目录Markdown索引，适合编辑器直接查看。
md=fopen(fullfile(out,'图像索引.md'),'w','n','UTF-8');assert(md>=0);cleanup=onCleanup(@()fclose(md));
fprintf(md,'# 教学诊断图像索引\n\n源运行：`%s`。先看全局/局部同步，再看同轮星座和留出导频，最后看CFO/SFO、CP、FFT和信道。\n\n',report.source_run);
for k=1:numel(report.figures),f=report.figures(k);fprintf(md,'- [%s](%s)：%s。限制：%s\n',f.title,f.file,f.purpose,f.limitations);end
end

function text=esc(text)
text=strrep(char(string(text)),'&','&amp;');text=strrep(text,'<','&lt;');text=strrep(text,'>','&gt;');text=strrep(text,'"','&quot;');
end
