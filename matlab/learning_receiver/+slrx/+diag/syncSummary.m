function result = syncSummary(sync, cfg, runDir)
%SYNCSUMMARY 只组织实际保存的候选；被算法跳过而未保存的粗峰不补造。
if nargin<3, runDir=cfg.run_dir; end
rows=struct('candidate_id',{},'raw_sample',{},'model_sample',{},'time_ms',{}, ...
    'pss_score',{},'sss_score',{},'joint_score',{},'coarse_score',{}, ...
    'cfo_hz',{},'status',{},'reason',{},'processing_qualified',{},'selected',{});
groups={'candidates','rejected'};
for group=1:2
    candidates=sync.(groups{group});
    for k=1:numel(candidates)
        item=candidates(k);
        raw=slrx.diag.coordinates('model_to_capture',item.start_sample_nominal,cfg);
        chosen=group==1 && item.start_sample_nominal==sync.selected.start_sample_nominal;
        reason=''; qualified=false;
        if group==1
            qualified=item.sss_metric>=cfg.minimum_processing_sss;
            state='accepted';
            if chosen, state='selected';
            elseif ~qualified, state='accepted_below_processing_gate'; reason='sss_below_configured_processing_gate';
            else, reason='other_qualified_candidate_not_selected_by_frame_rank'; end
            if isfield(item,'detection_index'), id=sprintf('accepted_%d',item.detection_index);
            else, id=sprintf('accepted_%d',k); end
        else
            state='rejected'; id=sprintf('rejected_%d',k);
            if isfield(item,'reason'), reason=item.reason; end
        end
        rows(end+1)=struct('candidate_id',id,'raw_sample',raw, ...
            'model_sample',item.start_sample_nominal, ...
            'time_ms',slrx.diag.coordinates('capture_to_ms',raw,cfg), ...
            'pss_score',item.pss_metric,'sss_score',item.sss_metric, ...
            'joint_score',item.coherent_pss_sss_metric,'coarse_score',item.coarse_metric, ...
            'cfo_hz',item.coarse_cfo_hz,'status',state,'reason',reason, ...
            'processing_qualified',qualified,'selected',chosen); %#ok<AGROW>
    end
end
selectedRaw=slrx.diag.coordinates('model_to_capture',sync.selected.start_sample_nominal,cfg);
assert(abs(selectedRaw-sync.selected.start_sample_capture)<1e-6,'slrx:DiagnosticCoordinate','保存坐标与运行配置不一致');
result=struct('candidates',rows,'selected',struct( ...
    'model_sample',sync.selected.start_sample_nominal,'raw_sample',selectedRaw, ...
    'nearest_raw_integer',round(selectedRaw),'has_fractional_raw_position',abs(selectedRaw-round(selectedRaw))>1e-8, ...
    'time_ms',slrx.diag.coordinates('capture_to_ms',selectedRaw,cfg), ...
    'pss_score',sync.selected.pss_metric,'sss_score',sync.selected.sss_metric, ...
    'joint_score',sync.selected.coherent_pss_sss_metric,'coarse_cfo_hz',sync.selected.coarse_cfo_hz), ...
    'model_fs_hz',cfg.model_fs_hz,'capture_fs_hz',cfg.capture_fs_hz, ...
    'window_first_capture_sample',cfg.first_complex_sample,'frame_rank',cfg.frame_rank, ...
    'trace_decimation',sync.scan.trace_decimation,'trace_max_is_not_true_global_max',true, ...
    'selection_rule','按时间排序后，在SSS达到处理门限的候选中取cfg.frame_rank；不等于相关分数最大者', ...
    'coverage','仅实际保存的接受/拒绝候选；未保存的重复粗峰/跳过尝试不补造', ...
    'local_zero_meaning','相对当前检测帧头的偏移0；不是原文件第0个采样点', ...
    'coarse_peak_location_available',false,'coarse_threshold',NaN,'threshold_source','not available');
source=fullfile(runDir,'source_code','+slrx','+alg','detectSync.m');
chosen=find([rows.selected],1);
result.selected.candidate_id=rows(chosen).candidate_id;
if exist(source,'file')
    match=regexp(fileread(source),'if\s+coarseMetric\s*<\s*([0-9.]+)','tokens','once');
    if ~isempty(match)
        result.coarse_threshold=str2double(match{1});
        result.threshold_source=source;
    end
end
end
