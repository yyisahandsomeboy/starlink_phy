function options = plotOptions(cfg)
%PLOTOPTIONS 主线和独立报告采用同一显示参数约定；无DSP选项。
refs=slrx.references(cfg);[~,n]=min(abs(refs.frequency_bins(refs.payload_rows)-64));
options=struct('symbols',cfg.display_data_column,'carrier_mode','payload', ...
    'frequency_band_mhz',[min(refs.frequency_bins) max(refs.frequency_bins)]*cfg.model_fs_hz/cfg.nfft/1e6, ...
    'geometry_id',[],'normalization','none','grid_columns',1:cfg.data_column_count+1, ...
    'selected_row',refs.payload_rows(n),'max_points',6000,'low_channel_fraction',.1, ...
    'show_figures',cfg.show_figures,'debug_plots',isfield(cfg,'debug_plots')&&cfg.debug_plots,'cfo_round',[]);
end
