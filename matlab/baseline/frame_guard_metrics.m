function frames = frame_guard_metrics(frames, fs_capture, fs_model, raw_iq, nominal_iq)
%FRAME_GUARD_METRICS Add model-predicted guard geometry and IQ diagnostics.
% frames = frame_guard_metrics(frames, fs_capture, fs_model, raw_iq, nominal_iq)
% preserves the frame array, its order, and every existing frame field, adding
% only frame_guard. Each frame supplies start_sample_nominal,
% start_sample_capture and sfo_ppm. raw_iq and nominal_iq are optional vectors
% on the original complex-sample and resampled model grids, respectively.
% An omitted/empty signal means capture coverage and measured power are unknown.
%
% All coordinates are continuous, 1-based sample coordinates. Window bounds
% are half-open [start,end); the end is EXCLUSIVE, not the last occupied sample.
% N captured samples have support [1,N+1), with integer sample centers 1:N.
% The actual integer centers inside [a,b) are ceil(a):ceil(b)-1, clipped to 1:N.
% Capture time is (coordinate-1)/fs_capture relative to raw_iq sample 1.
%
% Transmitter model: 302 symbols * 1056 samples at 240 MHz, one slot per 1/750 s.
% Guard = 1/750 - 302*1056/240e6 = 1088/240e6 = 4.533333333333333 us.
% The receiver's extract_grid map divides model offsets by (1+sfo_ppm*1e-6).
% BOTH occupied and guard lengths use that same division. No noise edge is
% detected here. Detection gaps can include skipped slots or another beam.
% The equal-duration preguard window ends at guard start: it covers the final
% 1056-sample symbol plus 32 preceding transmitter samples, before SFO mapping.

if nargin<4, raw_iq=[]; end
if nargin<5, nominal_iq=[]; end
validateattributes(fs_capture,{'numeric'},{'scalar','real','finite','positive'});
validateattributes(fs_model,{'numeric'},{'scalar','real','finite','positive'});
assert(isstruct(frames),'frame_guard_metrics:Frames','frames must be a struct array');
assert(isnumeric(raw_iq) && (isempty(raw_iq) || isvector(raw_iq)), ...
    'frame_guard_metrics:RawSignal','raw_iq must be a numeric vector or []');
assert(isnumeric(nominal_iq) && (isempty(nominal_iq) || isvector(nominal_iq)), ...
    'frame_guard_metrics:NominalSignal','nominal_iq must be a numeric vector or []');
if isempty(frames), return; end
required={'start_sample_nominal','start_sample_capture','sfo_ppm'};
assert(all(isfield(frames,required)), 'frame_guard_metrics:FrameFields', ...
    'Every frame must contain start_sample_nominal, start_sample_capture and sfo_ppm');
for j=1:numel(frames)
    validateattributes(frames(j).start_sample_nominal,{'numeric'},{'scalar','real','finite'});
    validateattributes(frames(j).start_sample_capture,{'numeric'},{'scalar','real','finite'});
    validateattributes(frames(j).sfo_ppm,{'numeric'},{'scalar','real','finite','>',-1e6});
end

transmitter_fs=240e6;
occupied_tx_samples=302*1056;
guard_tx_samples=1088;
slot_duration=1/750;
occupied_duration=occupied_tx_samples/transmitter_fs;
guard_duration=guard_tx_samples/transmitter_fs;
[~,chronological_order]=sort([frames.start_sample_capture]);

for position=1:numel(frames)
    j=chronological_order(position); frame=frames(j);
    scale=1/(1+frame.sfo_ppm*1e-6);
    occupied_model=occupied_tx_samples*(fs_model/transmitter_fs);
    guard_model=guard_tx_samples*(fs_model/transmitter_fs);
    occupied_capture=occupied_tx_samples*(fs_capture/transmitter_fs);
    guard_capture=guard_tx_samples*(fs_capture/transmitter_fs);
    guard_start_model=frame.start_sample_nominal+occupied_model*scale;
    guard_end_model=frame.start_sample_nominal+(fs_model/750)*scale;
    guard_start_capture=frame.start_sample_capture+occupied_capture*scale;
    guard_end_capture=frame.start_sample_capture+(fs_capture/750)*scale;
    preguard_start_model=guard_start_model-guard_model*scale;
    preguard_start_capture=guard_start_capture-guard_capture*scale;

    g=struct('role','codex_baseline','metric_version','frame-guard-v1', ...
        'endpoint_source','model_predicted','edge_detection_performed',false, ...
        'guard_window_interpretation','Sample-mapped nominal 1088-sample reference window; no measured noise edge', ...
        'frame_slot_mapping_assumption','Frame-slot effective rate equals waveform sample-map rate; unverified', ...
        'frame_clock_rate_estimated',false,'same_beam_identity_confirmed',false, ...
        'slot_count_interpretation','Nearest slot multiple under shared-rate assumption; not confirmed missed frames', ...
        'slot_residual_interpretation','Residual to shared-rate reference; not a frame-clock error estimate', ...
        'coordinate_convention','Continuous 1-based half-open [start,end); end exclusive', ...
        'time_origin','Raw complex sample 1 is time zero', ...
        'fs_capture_hz',fs_capture,'fs_model_hz',fs_model, ...
        'transmitter_model_fs_hz',transmitter_fs,'sfo_ppm',frame.sfo_ppm, ...
        'sample_map_scale',scale,'nominal_frame_interval_s',slot_duration, ...
        'nominal_occupied_duration_s',occupied_duration, ...
        'nominal_guard_duration_s',guard_duration, ...
        'nominal_occupied_model_samples',occupied_model, ...
        'nominal_guard_model_samples',guard_model, ...
        'nominal_frame_interval_model_samples',fs_model/750, ...
        'nominal_occupied_capture_samples',occupied_capture, ...
        'nominal_guard_capture_samples',guard_capture, ...
        'nominal_frame_interval_capture_samples',fs_capture/750, ...
        'mapped_occupied_model_samples',occupied_model*scale, ...
        'mapped_guard_model_samples',guard_model*scale, ...
        'mapped_frame_interval_model_samples',(fs_model/750)*scale, ...
        'mapped_occupied_capture_samples',occupied_capture*scale, ...
        'mapped_guard_capture_samples',guard_capture*scale, ...
        'mapped_frame_interval_capture_samples',(fs_capture/750)*scale, ...
        'mapped_occupied_duration_s',occupied_duration*scale, ...
        'mapped_guard_duration_s',guard_duration*scale, ...
        'mapped_frame_interval_s',slot_duration*scale, ...
        'guard_start_sample_nominal',guard_start_model, ...
        'guard_end_sample_nominal_exclusive',guard_end_model, ...
        'guard_start_sample_capture',guard_start_capture, ...
        'guard_end_sample_capture_exclusive',guard_end_capture, ...
        'guard_start_time_s',(guard_start_capture-1)/fs_capture, ...
        'guard_end_time_s',(guard_end_capture-1)/fs_capture, ...
        'preguard_start_sample_nominal',preguard_start_model, ...
        'preguard_end_sample_nominal_exclusive',guard_start_model, ...
        'preguard_start_sample_capture',preguard_start_capture, ...
        'preguard_end_sample_capture_exclusive',guard_start_capture, ...
        'preguard_start_time_s',(preguard_start_capture-1)/fs_capture, ...
        'preguard_end_time_s',(guard_start_capture-1)/fs_capture, ...
        'final_symbol_start_sample_nominal', ...
            frame.start_sample_nominal+(301*1056)*(fs_model/transmitter_fs)*scale, ...
        'final_symbol_start_sample_capture', ...
            frame.start_sample_capture+(301*1056)*(fs_capture/transmitter_fs)*scale, ...
        'preguard_description', ...
            'Equal guard duration preceding occupied end; final symbol plus preceding 32 transmitter samples', ...
        'detected_gap_interpretation', ...
            'Gap to another detection; may include undetected slots or another beam');
    g.raw_guard=window_metrics(raw_iq,guard_start_capture,guard_end_capture,fs_capture);
    g.raw_preguard=window_metrics(raw_iq,preguard_start_capture,guard_start_capture,fs_capture);
    g.nominal_guard=window_metrics(nominal_iq,guard_start_model,guard_end_model,fs_model);
    g.nominal_preguard=window_metrics(nominal_iq,preguard_start_model,guard_start_model,fs_model);
    [g.raw_guard_to_preguard_power_ratio,g.raw_guard_to_preguard_power_db]= ...
        power_comparison(g.raw_guard.mean_power,g.raw_preguard.mean_power);
    [g.nominal_guard_to_preguard_power_ratio,g.nominal_guard_to_preguard_power_db]= ...
        power_comparison(g.nominal_guard.mean_power,g.nominal_preguard.mean_power);
    g.raw_power_comparison_uses_partial_window=partial_comparison(g.raw_guard,g.raw_preguard);
    g.nominal_power_comparison_uses_partial_window=partial_comparison(g.nominal_guard,g.nominal_preguard);

    spacing_fields={'previous_detected_start_interval_model_samples', ...
        'previous_detected_start_interval_capture_samples','previous_detected_start_interval_s', ...
        'previous_estimated_slot_count','previous_reference_sfo_ppm', ...
        'previous_slot_interval_residual_model_samples', ...
        'previous_slot_interval_residual_capture_samples','previous_slot_interval_residual_s', ...
        'next_detected_start_interval_model_samples','next_detected_start_interval_capture_samples', ...
        'next_detected_start_interval_s','next_estimated_slot_count','next_reference_sfo_ppm', ...
        'next_slot_interval_residual_model_samples','next_slot_interval_residual_capture_samples', ...
        'next_slot_interval_residual_s','gap_to_next_detected_frame_model_samples', ...
        'gap_to_next_detected_frame_capture_samples','gap_to_next_detected_frame_s'};
    for k=1:numel(spacing_fields), g.(spacing_fields{k})=NaN; end
    % A spacing uses the earlier frame's local SFO for slot extrapolation.
    if position>1
        previous=frames(chronological_order(position-1));
        g=add_spacing(g,'previous',previous,frame,fs_capture,fs_model);
    end
    if position<numel(frames)
        next=frames(chronological_order(position+1));
        g=add_spacing(g,'next',frame,next,fs_capture,fs_model);
        g.gap_to_next_detected_frame_model_samples=next.start_sample_nominal-guard_start_model;
        g.gap_to_next_detected_frame_capture_samples=next.start_sample_capture-guard_start_capture;
        g.gap_to_next_detected_frame_s=g.gap_to_next_detected_frame_capture_samples/fs_capture;
    end
    frames(j).frame_guard=g;
end
end

function w=window_metrics(signal,first,last,fs)
first_integer=ceil(first); last_integer=ceil(last)-1;
expected_count=max(0,last_integer-first_integer+1);
w=struct('start_sample',first,'end_sample_exclusive',last, ...
    'start_time_s',(first-1)/fs,'end_time_s',(last-1)/fs, ...
    'duration_samples',last-first,'duration_s',(last-first)/fs, ...
    'signal_supplied',~isempty(signal),'capture_sample_count',NaN, ...
    'in_capture',NaN,'truncated',NaN,'truncated_before',NaN,'truncated_after',NaN, ...
    'truncated_before_samples',NaN,'truncated_after_samples',NaN, ...
    'truncated_before_s',NaN,'truncated_after_s',NaN, ...
    'first_integer_sample_requested',first_integer,'last_integer_sample_requested',last_integer, ...
    'expected_integer_sample_count',expected_count,'actual_integer_sample_count',NaN, ...
    'missing_integer_sample_count',NaN,'sample_indices',zeros(0,1),'samples',zeros(0,1), ...
    'rms',NaN,'mean_power',NaN);
if isempty(signal), return; end
count=numel(signal);
w.capture_sample_count=count;
w.in_capture=first>=1 && last<=count+1;
w.truncated=~w.in_capture;
w.truncated_before=first<1;
w.truncated_after=last>count+1;
% Missing continuous durations are bounded by the whole window length.
w.truncated_before_samples=max(0,min(last,1)-first);
w.truncated_after_samples=max(0,last-max(first,count+1));
w.truncated_before_s=w.truncated_before_samples/fs;
w.truncated_after_s=w.truncated_after_samples/fs;
available_first=max(1,first_integer); available_last=min(count,last_integer);
if available_first<=available_last
    w.sample_indices=(available_first:available_last)';
    values=signal(w.sample_indices); w.samples=values(:);
    w.mean_power=mean(abs(w.samples).^2);
    w.rms=sqrt(w.mean_power);
end
w.actual_integer_sample_count=numel(w.sample_indices);
w.missing_integer_sample_count=expected_count-w.actual_integer_sample_count;
end

function [ratio,db]=power_comparison(guard_power,preguard_power)
ratio=NaN; db=NaN;
if isnan(guard_power) || isnan(preguard_power), return; end
ratio=guard_power/preguard_power;
db=10*log10(ratio);
end

function partial=partial_comparison(guard,preguard)
partial=NaN;
if guard.signal_supplied && preguard.signal_supplied
    partial=guard.truncated || preguard.truncated;
end
end

function g=add_spacing(g,prefix,earlier,later,fs_capture,fs_model)
interval_capture=later.start_sample_capture-earlier.start_sample_capture;
interval_model=later.start_sample_nominal-earlier.start_sample_nominal;
scale=1/(1+earlier.sfo_ppm*1e-6);
slot_capture=(fs_capture/750)*scale;
slot_model=(fs_model/750)*scale;
slots=round(interval_capture/slot_capture);
g.([prefix '_detected_start_interval_model_samples'])=interval_model;
g.([prefix '_detected_start_interval_capture_samples'])=interval_capture;
g.([prefix '_detected_start_interval_s'])=interval_capture/fs_capture;
g.([prefix '_estimated_slot_count'])=slots;
g.([prefix '_reference_sfo_ppm'])=earlier.sfo_ppm;
g.([prefix '_slot_interval_residual_model_samples'])=interval_model-slots*slot_model;
g.([prefix '_slot_interval_residual_capture_samples'])=interval_capture-slots*slot_capture;
g.([prefix '_slot_interval_residual_s'])=(interval_capture-slots*slot_capture)/fs_capture;
end
