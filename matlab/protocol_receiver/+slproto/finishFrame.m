function result = finishFrame(grid,calibrated,R,calibration,pn,headers,coding,opt)
%FINISHFRAME 组织已有步骤与只读不变量；顺序教学不提前计算后续步骤。
c=slproto.coordinates();after=calibrated.*conj(R);values=after(c.payload_rows,2:301);stream=values(:);
before=calibrated(c.payload_rows,2:301);
restored=calibrated;restored(:,2:301)=calibrated(:,2:301).*exp(1j*(ones(1024,1)*calibration.phase_intercept_rad+c.bins*calibration.phase_slope_rad_per_bin));
calibrationError=norm(restored-grid,'fro')/max(norm(grid,'fro'),eps);
headerMask=1:min(228,numel(stream));a=stream(headerMask);v=before(:);v=v(headerMask);
wrong=circshift(R,13,1);w=calibrated.*conj(wrong);w=w(c.payload_rows,2:301);w=w(headerMask);
result=struct('version',opt.version,'owner','codex_baseline','pn',pn,'calibration',calibration, ...
    'headers',headers,'code5',coding,'options',opt,'calibrated_grid',calibrated, ...
    'derotated_grid',after,'payload_stream',stream,'reference_grid',R, ...
    'axis_energy_before',sum(real(v).^2)/sum(abs(v).^2), ...
    'axis_energy_after',sum(real(a).^2)/sum(abs(a).^2), ...
    'wrong_reference_axis_energy',sum(real(w).^2)/sum(abs(w).^2), ...
    'rotation_roundtrip_relative_error',norm(calibrated-after.*R,'fro')/max(norm(calibrated,'fro'),eps), ...
    'calibration_roundtrip_relative_error',calibrationError,'application_plaintext_recovered',false, ...
    'full_payload_FEC_supported',false,'second_header_semantics','conditional; unknown format labels retained');
assert(result.rotation_roundtrip_relative_error<1e-12&&calibrationError<1e-12);
end
